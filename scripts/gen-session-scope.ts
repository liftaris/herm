#!/usr/bin/env bun
// Generate src/context/session-scope.gen.ts — the set of RPC methods whose
// Params model (or a base it inherits) declares `session_id`.
//
// The gateway's Params models are `extra="forbid"`, so injecting `session_id`
// into a method that does not declare it answers 4000 and takes the call down.
// The client must therefore know which methods accept the field, and that
// answer belongs to the Hermes contracts — not to a hand-maintained list that
// silently rots when the backend moves.
//
// Boundary: static Python AST over an explicit HERMES_AGENT_ROOT. No imports,
// no gateway startup, no HERMES_HOME reads, no producer execution — the same
// contract scripts/hermes-source.ts holds.
//
//   bun scripts/gen-session-scope.ts --agent <path> [--check]

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { gitSha } from "./schema-source"
import { find } from "./hermes-source"

const arg = (name: string) => {
  const pos = Bun.argv.indexOf(name)
  if (pos < 0) return ""
  const val = Bun.argv[pos + 1]
  if (!val || val.startsWith("--")) {
    console.error(`gen-session-scope: ${name} requires a value`)
    process.exit(2)
  }
  return val
}

const input = arg("--agent") || process.env.HERMES_AGENT_ROOT
if (!input) {
  console.error("gen-session-scope: pass --agent or HERMES_AGENT_ROOT")
  process.exit(2)
}
const root = find(input)
// find() guarantees tui_gateway/ exists; the contracts package is where every
// RPC Params model lives.
//
// NOTE: this package is newer than hermes.contract.json's pin (4da7b9ee,
// 2026-07-28), which predates the strict `extra="forbid"` Params contracts
// entirely. So this generator cannot run against the pinned checkout the CI
// contract step uses; it needs a Hermes tree at or after the contracts package
// landed. Bumping the pin is what lets the CI gate below be wired in.
const contracts = join(root, "tui_gateway", "contracts")
if (!existsSync(contracts)) {
  console.error(
    `gen-session-scope: no contracts package under ${root}\n` +
    `  This Hermes tree predates tui_gateway/contracts/ (the strict Params models).\n` +
    `  Point --agent at a checkout that has it (the running backend does).`,
  )
  process.exit(2)
}

// Walk the contract classes, resolve `session_id` through base classes, and
// collect every registered method that admits it.
const py = String.raw`
import ast, json, re, sys
from pathlib import Path

cdir = Path(${JSON.stringify(contracts)})
SKIP = {"Params", "Result", "Payload", "BaseModel", "OpenModel"}
classes = {}

for p in sorted(cdir.glob("*.py")):
    try:
        tree = ast.parse(p.read_text(encoding="utf-8"), filename=str(p))
    except SyntaxError as exc:
        print(json.dumps({"error": f"{p.name}:{exc.lineno}: {exc.msg}"}))
        sys.exit(0)
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        fields, bases = [], []
        for b in node.bases:
            if isinstance(b, ast.Name):
                bases.append(b.id)
            elif isinstance(b, ast.Attribute):
                bases.append(b.attr)
        for st in node.body:
            if isinstance(st, ast.AnnAssign) and isinstance(st.target, ast.Name):
                fields.append(st.target.id)
        classes[node.name] = {"bases": bases, "fields": fields}


def scoped(name, seen=None):
    seen = seen or set()
    if name in seen:
        return False
    seen.add(name)
    c = classes.get(name)
    if not c:
        return False
    if "session_id" in c["fields"]:
        return True
    return any(scoped(b, seen) for b in c["bases"] if b not in SKIP)


methods = {}
for p in sorted(cdir.glob("*.py")):
    text = p.read_text(encoding="utf-8")
    for m in re.finditer(r'method\(\s*"([^"]+)"\s*,\s*params=(\w+)', text):
        methods.setdefault(m.group(1), m.group(2))

if not methods:
    print(json.dumps({"error": "no registered methods found in contracts/"}))
    sys.exit(0)

declared = sorted(k for k, v in methods.items() if scoped(v))
print(json.dumps({"total": len(methods), "declared": declared}))
`

const proc = Bun.spawnSync(["python3", "-c", py])
if (proc.exitCode !== 0) {
  console.error(`gen-session-scope: extraction crashed\n${new TextDecoder().decode(proc.stderr)}`)
  process.exit(2)
}
const data = JSON.parse(new TextDecoder().decode(proc.stdout)) as
  | { error: string }
  | { total: number; declared: string[] }
if ("error" in data) {
  console.error(`gen-session-scope: ${data.error}`)
  process.exit(2)
}

const sha = gitSha(root)
const body = [
  "// Generated by scripts/gen-session-scope.ts — do not edit by hand.",
  `// Source: hermes-agent@${sha} tui_gateway/contracts/`,
  `// RPC methods: ${data.total}; declaring session_id: ${data.declared.length}`,
  "",
  `export const SESSION_SCOPE_SOURCE_REVISION = ${JSON.stringify(sha)}`,
  `export const SESSION_SCOPED_METHOD_COUNT = ${data.total}`,
  "",
  "// Methods whose Params model, or a base it inherits, declares session_id.",
  "// The client injects the active session into exactly these.",
  "export const SESSION_SCOPED: readonly string[] = [",
  ...data.declared.map(name => `  ${JSON.stringify(name)},`),
  "]",
  "",
].join("\n")

const target = resolve(arg("--out") || join(import.meta.dir, "..", "src", "context", "session-scope.gen.ts"))
const stale = !existsSync(target) || readFileSync(target, "utf8") !== body

if (Bun.argv.includes("--check")) {
  if (stale) console.error(`gen-session-scope: ${target} is stale (run: bun run gen-session-scope)`)
  process.exit(stale ? 1 : 0)
}

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, body)
console.error(
  `gen-session-scope: wrote ${relative(process.cwd(), target)} ` +
  `(${data.declared.length}/${data.total} methods declare session_id) from ${root}`,
)
